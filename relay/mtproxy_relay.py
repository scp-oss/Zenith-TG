#!/usr/bin/env python3
"""mtproxy_relay.py -- настоящий, explicit-настроенный MTProxy (с секретом),
запуск оригинального `vendor/tg_ws_proxy.py` (Flowseal/tg-ws-proxy, MIT,
СОВЕРШЕННО НЕ ИЗМЕНЁН, только импортирован как модуль) как отдельного
сервиса рядом с `transparent_relay.py`.

Живой случай, из-за которого это появилось (2026-08-22, см. CLAUDE.md
"Android MTProto investigation" за полным разбором): `transparent_relay.py`
-- прозрачный, БЕЗ секрета коннектор -- работает на iPhone, но на Android
клиент вообще не шлёт тот формат (сырой obfuscated2), который этот
коннектор понимает. Байтовый захват показал настоящий TLS ClientHello к
реальным IP датацентров вместо этого -- то есть Android, оставленный без
явно настроенного прокси, ведёт себя иначе, чем предполагает "прозрачная"
идея всего проекта. Раньше (до адаптации под no-secret-транспарентный
режим) этот же апстрим-код в ОРИГИНАЛЬНОМ виде -- настоящий MTProxy-протокол
с секретом, клиент явно настроен через `tg://proxy?...` ссылку/QR --
подтверждённо работал одинаково на обеих платформах. Это его прямой
перезапуск, не переписанная копия -- никакого риска рассинхронизации с
апстримом сверх того, что уже есть у остальных vendor/-модулей.

В отличие от transparent_relay.py (слушает ТОЛЬКО на loopback, потому что
у него в принципе нет контроля доступа без секрета -- см. предупреждение в
его докстринге), этот сервис ДОЛЖЕН слушать на публичном интерфейсе:
секрет — это и есть контроль доступа, тут нет REDIRECT/загадывания "прямое
это соединение или нет", клиент просто идёт по явной ссылке на конкретный
host:port с конкретным секретом.

Запуск (см. также tg-mtproxy-relay.service):
    ./mtproxy_relay.py --host 0.0.0.0 --port 9443 --secret <32 hex>

Без --secret сгенерирует случайный и выведет его в лог вместе с готовой
tg://proxy-ссылкой -- один раз запусти вручную, чтобы её получить, потом
зафиксируй тем же --secret в systemd-юните (иначе при каждом рестарте
ссылка будет новой и все клиенты отвалятся)."""
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))  # relay/vendor/*

from vendor.tg_ws_proxy import main  # noqa: E402  (апстримный, не наш код)

if __name__ == '__main__':
    main()
